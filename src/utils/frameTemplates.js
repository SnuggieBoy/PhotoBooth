// LocalStorage Persistence Helpers for Custom Uploaded Frames
const STORAGE_KEY = 'snuggie_photobooth_custom_frames'

export function loadSavedCustomFrames() {
  if (typeof window === 'undefined') return []
  try {
    const raw = localStorage.getItem(STORAGE_KEY)
    if (!raw) return []
    const parsed = JSON.parse(raw)
    return Array.isArray(parsed) ? parsed : []
  } catch (err) {
    console.warn('Could not load custom frames from localStorage:', err)
    return []
  }
}

export function saveCustomFrameToStorage(frame) {
  if (typeof window === 'undefined') return
  try {
    const existing = loadSavedCustomFrames()
    // Don't add duplicate
    const filtered = existing.filter((f) => f.id !== frame.id)
    const updated = [frame, ...filtered].slice(0, 10) // keep up to 10 custom frames
    localStorage.setItem(STORAGE_KEY, JSON.stringify(updated))
  } catch (err) {
    console.warn('Could not save custom frame to localStorage:', err)
  }
}
